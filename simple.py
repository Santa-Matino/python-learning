# 变量是可以付值的标签，指向特定值

#字符串
#little方法 首字母大写
name='aden'
print(f'Hi, {name.title()}')

# upper lower 方法 全局大小写
name='aden'
print(f'Hi, {name.upper()}')
print(f'Hi, {name.lower()}')

#字符串中插入变量 f'' format 格式设置
print(f'Hi, {name.title().lower()}')

# 制表符\t 换行符\n
print('languages:\n\tpython\n\tjava\n\tjavascript')

#删除空白 rstrip lstrip strip 尾 首 尾➕首
name=(' aden ')
print(name.strip())
print(name.rstrip())
print(name.lstrip())

#数 加减乘除+-*/
print(2+3)
# 浮点数 下划线
print(0.1+0.1)
print(3/7)
print(4/2)
print(14_000_000)
print('x,y,z=1,2,3')#终端
#常量 全大写
NAME='5000'
print(f'Hi, {NAME}')
